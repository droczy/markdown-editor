// swift-tools-version: 6.2
// Platform-specific logic of the macOS app that can be tested without
// launching the app. Linked statically into the app target.
//
// Requires the generated Rust core: run scripts/build-core-xcframework.sh
// from the repository root first.

import PackageDescription

let package = Package(
    name: "MarkdownEditorKit",
    platforms: [.macOS(.v26)],
    products: [
        .library(name: "MarkdownEditorKit", targets: ["MarkdownEditorKit"])
    ],
    targets: [
        // Rust core as a static library with C headers (generated).
        .binaryTarget(
            name: "MarkdownEditorCoreFFI",
            path: "Generated/MarkdownEditorCoreFFI.xcframework"
        ),
        // Swift bindings generated by UniFFI. Internal to this package: the
        // app only uses the wrapper API of MarkdownEditorKit.
        .target(
            name: "MarkdownEditorCore",
            dependencies: ["MarkdownEditorCoreFFI"],
            path: "Generated/Swift"
        ),
        .target(
            name: "MarkdownEditorKit",
            dependencies: ["MarkdownEditorCore"],
            swiftSettings: [.treatAllWarnings(as: .error)]
        ),
        .testTarget(
            name: "MarkdownEditorKitTests",
            dependencies: ["MarkdownEditorKit"],
            swiftSettings: [.treatAllWarnings(as: .error)]
        ),
    ],
    swiftLanguageModes: [.v6]
)
